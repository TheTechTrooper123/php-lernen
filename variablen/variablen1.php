<?php 
// eine Variable deklarieren und initialisieren
$var1 = 1;
$var2 = 2;
$aussage = "Die Summe von " . $var1 . " und " . $var2 . " ist: ";

// die beiden Variablen addieren und das Ergebnis einer neuen Variable zuweisen
